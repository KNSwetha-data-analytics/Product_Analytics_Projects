1. Revenue Overview: 
   - Total Revenue (for this data): 1,104,983.78
   - Total purchase events : 3,639
   - Average Purchase Value (APV): 303.65
   
2. Category Analysis: 
   - electronics.smartphones contributes 67.88% of the total revenue.
   - computer.notebook follows with 4.74% contribution.
   - Revenue is heavily concentrated in the smartphone category.
   
3. Brand Analysis:
   - Apple contributes 45.58% of total revenue.
   - Samsung follows with 21.42% contribution.
   - Approximately two-thirds of the revenue is generated by these two brands
   
4. Product Analysis: 
   - Top 5 products belong to the smartphones category of brands Apple and Samsung.
   
5. Business Implications:
   - Revenue generation is highly concentrated in smartphone.
   - Apple is the dominant revenue-driving brand. 
   - Business may face category and brand concentration risk. 

*/
USE product_growth_analytics; 

# Total Revenue
SELECT SUM(price)
FROM ecommerce_events_01
WHERE event_type = "purchase";

# Number of orders
SELECT COUNT(*) AS number_of_orders
FROM ecommerce_events_01
WHERE event_type = "purchase"; 
# COUNT(*) is used as this dataset did not have an order_id column.

# AOV
SELECT SUM(price) / COUNT(*) AS aov    
FROM ecommerce_events_01
WHERE event_type = "purchase"; 
# This is equivatent to AVG(price) when event_type = "purchase", i.e. Average Purchase Value.  

# Revenue by Category
SELECT category_id, 
	   COALESCE(NULLIF(category_code, ''), "unknown") AS category_code, 
       SUM(price) AS category_revenue 
FROM ecommerce_events_01
WHERE event_type = "purchase"
GROUP BY category_id, 
		 COALESCE(NULLIF(category_code, ''), "unknown")
ORDER BY category_revenue DESC;

# Revenue Distribution by category 
SELECT category_id, 
	   COALESCE(NULLIF(category_code, ''), "unknown") AS category_code, 
       ROUND(SUM(price) * 100.0 /
			 (SELECT SUM(price) 
              FROM ecommerce_events_01 
			  WHERE event_type = "purchase"), 2) AS category_distribution 
FROM ecommerce_events_01
WHERE event_type = "purchase"
GROUP BY category_id, 
		 COALESCE(NULLIF(category_code, ''), "unknown")
ORDER BY category_distribution DESC;

# Revenue by brand
SELECT COALESCE(NULLIF(brand, ''), "unknown") AS brand, 
       SUM(price) AS Revenue_per_brand
FROM ecommerce_events_01
WHERE event_type = "purchase"
GROUP BY COALESCE(NULLIF(brand, ''), "unknown")
ORDER BY Revenue_per_brand DESC;

# Revenue distribution by brand
SELECT COALESCE(NULLIF(brand, ''), "unknown") AS brand, 
       ROUND(SUM(price) * 100.0 /
             (SELECT SUM(price) 
              FROM ecommerce_events_01
			  WHERE event_type = "purchase"), 2) AS brand_distribution
FROM ecommerce_events_01
WHERE event_type = "purchase"
GROUP BY COALESCE(NULLIF(brand, ''), "unknown")
ORDER BY brand_distribution DESC;

# Top products by revenue
SELECT product_id, 
       SUM(price) AS product_Revenue 
FROM ecommerce_events_01
WHERE event_type = "purchase" 
GROUP BY product_id 
ORDER BY product_Revenue DESC; 

# Revenue distribution by product
SELECT product_id, 
       ROUND(SUM(price) * 100.0 /
             (SELECT SUM(price) 
              FROM ecommerce_events_01
			  WHERE event_type = "purchase"), 2) AS product_distribution
FROM ecommerce_events_01
WHERE event_type = "purchase"
GROUP BY product_id
ORDER BY product_distribution DESC;

